def glyph(ch):
    o = ord(ch)
    if o < 32 or o > 127:
        o = 63
    i = (o - 32) * 8
    return _FONT[i : i + 8]


def text_width(s, scale=1):
    return len(s) * 8 * scale


@micropython.viper
def _render(buf: ptr8, font: ptr8, txt: ptr8, n: int, fg: int, bg: int):
    w2 = n * 16
    fh = (fg >> 8) & 0xFF
    fl = fg & 0xFF
    bh = (bg >> 8) & 0xFF
    bl = bg & 0xFF
    for i in range(n):
        o = txt[i]
        if o < 32 or o > 127:
            o = 63
        g = (o - 32) * 8
        for row in range(8):
            bits = font[g + row]
            p = row * w2 + i * 16
            mask = 0x80
            while mask:
                if bits & mask:
                    buf[p] = fh
                    buf[p + 1] = fl
                else:
                    buf[p] = bh
                    buf[p + 1] = bl
                p += 2
                mask >>= 1


def draw_text(tft, s, x, y, color, bg=None, scale=1):
    # Fond connu : une seule image envoyee a l'ecran au lieu d'un rectangle par trait.
    if bg is not None and scale == 1 and x >= 0 and y >= 0 and y + 8 <= tft.height:
        b = s.encode()
        n = len(b)
        if n and n == len(s) and x + n * 8 <= tft.width:
            buf = bytearray(n * 128)
            _render(buf, _FONT, b, n, color, bg)
            tft.blit(buf, x, y, n * 8, 8)
            return x + n * 8
    for ch in s:
        g = glyph(ch)
        for row in range(8):
            bits = g[row]
            if bg is not None:
                tft.fill_rect(x, y + row * scale, 8 * scale, scale, bg)
            col = 0
            while col < 8:
                if bits & (0x80 >> col):
                    start = col
                    while col < 8 and (bits & (0x80 >> col)):
                        col += 1
                    tft.fill_rect(x + start * scale, y + row * scale, (col - start) * scale, scale, color)
                else:
                    col += 1
        x += 8 * scale
    return x
